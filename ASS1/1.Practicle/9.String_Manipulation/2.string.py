# Write a Python program that manipulates and prints strings using various string methods.

a='Hello World'

print(len(a))
print(a.lower())
print(a.upper())
print(a.count('l'))
print(a.capitalize())
print(a.title())
print(a.strip())
print(a.startswith('H'))
print(a.endswith('k'))
print(a.replace('Hello','Namaste'))
print(a.isalpha())
print(a.isalnum())
print(a.isnumeric())

